const sortedKeys = Object.keys(table).map(Number).sort((a, b) => a - b);
const MIN = sortedKeys[0];
const MAX = sortedKeys[sortedKeys.length - 1];

function lookup(amount) {
    if (table[amount]) return { amount, price: table[amount], rounded: false };
    if (amount < MIN || amount > MAX) return null;
    const nearest = sortedKeys.reduce((p, c) =>
        Math.abs(c - amount) < Math.abs(p - amount) ? c : p
    );
    return { amount: nearest, price: table[nearest], rounded: nearest !== amount };
}

// Extracts the first plausible integer from a freeform string.
// Handles: "1500", "1,500", "1.500", "1 500", "quiero 1500 robux", etc.
function extractNumber(text) {
    if (!text || typeof text !== 'string') return null;
    // Strip everything except digits, collapse to a single run
    const digits = text.replace(/[^\d]/g, '');
    if (!digits) return null;
    const n = parseInt(digits, 10);
    return isNaN(n) || n <= 0 ? null : n;
}

// Extracts a decimal number from freeform input.
// Handles: "500", "150.50", "150,50", "$200", etc.
function extractDecimal(text) {
    if (!text || typeof text !== 'string') return null;
    const cleaned = text.trim().replace(/[$\s]/g, '');
    // Treat comma as decimal separator if it looks like "150,50" (no dot present)
    const normalized = /,\d{1,2}$/.test(cleaned) && !cleaned.includes('.')
        ? cleaned.replace(',', '.')
        : cleaned.replace(/,/g, '');
    const n = parseFloat(normalized);
    return isNaN(n) || n <= 0 ? null : n;
}

function parsePrice(str) {
    return parseFloat(str.replace(/[$,]/g, ''));
}

// Given a MXN budget, returns the highest robux package the user can afford.
function lookupByBudget(budget) {
    if (isNaN(budget) || budget <= 0) return null;
    let bestRobux = 0;
    let bestPrice = null;
    for (const [robuxStr, priceStr] of Object.entries(table)) {
        const price = parsePrice(priceStr);
        const robux = Number(robuxStr);
        if (price <= budget && robux > bestRobux) {
            bestRobux = robux;
            bestPrice = priceStr;
        }
    }
    return bestRobux > 0 ? { robux: bestRobux, price: bestPrice } : null;
}

